import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root = path.dirname(fileURLToPath(import.meta.url));
const original = process.argv[2];
const historical = path.join(root, 'historical');
const sha = file => createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const archivedPath = relative => relative === 'reference/README.md' ? 'reference/README.original.txt' : relative;
const previous = JSON.parse(fs.readFileSync(path.join(root, 'results/provenance.json')));
const manifest = previous.manifest.map(entry => {
  const copied = path.join(historical, archivedPath(entry.file));
  const copiedSha256 = sha(copied);
  assert.equal(copiedSha256, entry.originalSha256, entry.file);
  if (original) assert.equal(sha(path.join(original, entry.file)), copiedSha256, entry.file);
  return { ...entry, archivedFile: archivedPath(entry.file), copiedSha256 };
});
const raw = JSON.parse(fs.readFileSync(path.join(historical, 'results/raw.json')));
const reproduced = JSON.parse(fs.readFileSync(path.join(root, 'results/reproduced-580/results/raw.json')));
assert.equal(raw.assertions, 580); assert.equal(raw.checks.length, 580); assert(raw.checks.every(c => c.pass));
assert.equal(reproduced.assertions, 580); assert.deepEqual(reproduced.checks, raw.checks);
const omitMeasurement = data => JSON.parse(JSON.stringify(data, (key, value) => ['timestamp', 'dpMs', 'ms', 'memoryBytes'].includes(key) ? undefined : value));
assert.deepEqual(omitMeasurement(reproduced), omitMeasurement(raw));
fs.writeFileSync(path.join(root, 'results/provenance.json'), JSON.stringify({ historicalFilesMatched: manifest.length, historicalChecks: 580, reproducedChecks: 580, numericContentReproduced: true, excludedNondeterministicFields: ['timestamp', 'dpMs', 'ms', 'memoryBytes'], manifest }, null, 2) + '\n');
console.log(`PASS: ${manifest.length} historical files SHA-identical; 580 checks reproduced; numerical raw matches after excluding timing/environment measurements.`);
